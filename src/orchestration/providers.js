// Provider-neutral model adapter registry.
// Only the deterministic mock provider is enabled. Real providers are declared
// but disabled until credentials are approved and configured as Worker secrets.

export const PROVIDER_CATALOG = Object.freeze({
  mock: Object.freeze({
    label: "ZUVANE Mock Provider",
    enabled: true,
    models: Object.freeze(["mock-deterministic-1"]),
    description: "Deterministic in-Worker adapter for verifying orchestration. Makes no external calls and incurs no cost."
  }),
  openai: Object.freeze({
    label: "OpenAI",
    enabled: false,
    models: Object.freeze(["gpt-4.1-mini"]),
    description: "Not configured. Requires an approved API key stored as a Worker secret."
  }),
  anthropic: Object.freeze({
    label: "Anthropic",
    enabled: false,
    models: Object.freeze(["claude-sonnet"]),
    description: "Not configured. Requires an approved API key stored as a Worker secret."
  })
});

export class ProviderError extends Error {
  constructor(message, { retryable = true } = {}) {
    super(message);
    this.retryable = retryable;
  }
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const KEYWORD_TOOLS = [
  ["notes.search", /\b(notes?|context|catatan|konteks)\b/i],
  ["web.search", /\b(research|search|find|investigate|cari|riset)\b/i],
  ["document.draft", /\b(draft|write|document|report|tulis|laporan|dokumen)\b/i],
  ["calendar.create_event", /\b(meeting|schedule|calendar|jadwal|rapat)\b/i],
  ["email.send", /\b(email|e-mail|send|kirim)\b/i]
];

function directives(text) {
  return {
    failAlways: /\[mock:fail\]/i.test(text),
    failOnce: /\[mock:fail-once\]/i.test(text),
    slow: /\[mock:slow\]/i.test(text),
    forcedTool: (text.match(/\[mock:tool=([a-z_.]+)\]/i) || [])[1] || null
  };
}

/**
 * Deterministic mock provider. Receives ONLY the tools the agent is allowed to use
 * (least privilege); the gateway re-checks permissions before every tool call.
 */
export const mockProvider = Object.freeze({
  id: "mock",
  plan({ task, allowedTools }) {
    const text = `${task.title}\n${task.description || ""}`;
    const d = directives(text);
    const steps = [{ type: "model", action: "analyze" }];
    for (const [tool, pattern] of KEYWORD_TOOLS) {
      if (allowedTools.includes(tool) && pattern.test(text)) steps.push({ type: "tool", tool });
    }
    if (d.forcedTool) steps.push({ type: "tool", tool: d.forcedTool });
    steps.push({ type: "model", action: "summarize" });
    return steps;
  },
  async invoke({ action, task, attempt, timeoutMs, context }) {
    const text = `${task.title}\n${task.description || ""}`;
    const d = directives(text);
    if (d.slow) await sleep(Math.min(timeoutMs + 50, 30_050));
    if (d.failAlways) throw new ProviderError("Mock provider returned a simulated failure.");
    if (d.failOnce && attempt === 1) throw new ProviderError("Mock provider returned a transient failure.");
    if (action === "analyze") {
      return { summary: `Analyzed task "${task.title}" (${task.priority} priority).`, tokens: 120 };
    }
    const toolNotes = context.tool_results.map((result) => `- ${result.tool}: ${result.summary}`).join("\n");
    return {
      summary: `Completed "${task.title}". ${context.tool_results.length} tool step(s) executed.`,
      text: `Result for "${task.title}"\n${toolNotes || "- No tools were required."}\nGenerated by the deterministic mock provider; no external model was called.`,
      tokens: 240
    };
  }
});

export function getProvider(id) {
  const entry = PROVIDER_CATALOG[id];
  if (!entry || !entry.enabled) return null;
  if (id === "mock") return mockProvider;
  return null;
}

export async function withTimeout(promise, ms, message = "Provider call timed out.") {
  let timer;
  try {
    return await Promise.race([
      promise,
      new Promise((_, reject) => { timer = setTimeout(() => reject(new ProviderError(message)), ms); })
    ]);
  } finally {
    clearTimeout(timer);
  }
}

export function providerCatalogView() {
  return Object.entries(PROVIDER_CATALOG).map(([id, p]) => ({ id, label: p.label, enabled: p.enabled, models: [...p.models], description: p.description }));
}
